-- Second Brain Bot: Postgres schema, isolated in schema "brain" of the n8n DB.
-- Apply: podman exec -i n8n_postgres_1 psql -U n8n -d n8n -v ON_ERROR_STOP=1 < migrations/001_init.sql
BEGIN;
CREATE SCHEMA IF NOT EXISTS brain;
SET search_path = brain;

-- One row per incoming message ("batch"). Finance items wait here for ✅; instant items are
-- recorded too so ✏️ / ↩️ / /undo know what was created.
CREATE TABLE pending (
  id                  text PRIMARY KEY,              -- generated by the bot
  chat_id             bigint      NOT NULL,
  type                text        NOT NULL CHECK (type IN ('finance','instant','mixed')),
  -- {source:{input_type,text,transcript,file_id,mime,message_date},
  --  items:[{idx,type,data,confidence,warnings[],state,notion:{id,url,kind}}]}
  payload             jsonb       NOT NULL,
  telegram_message_id bigint,
  status              text        NOT NULL DEFAULT 'open'
                      CHECK (status IN ('open','saving','saved','retrying','cancelled','expired','undone')),
  attempts            int         NOT NULL DEFAULT 0,
  last_error          text,
  reminded_at         timestamptz,
  saved_at            timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX pending_status_idx ON pending (status, created_at);
CREATE INDEX pending_saved_idx  ON pending (chat_id, saved_at DESC) WHERE status = 'saved';

-- Button state; Telegram callback_data only carries 'cb:<token>' (64-byte limit).
CREATE TABLE callbacks (
  token      text PRIMARY KEY,
  chat_id    bigint NOT NULL,
  action     text   NOT NULL,
  data       jsonb  NOT NULL DEFAULT '{}',
  pending_id text REFERENCES pending(id) ON DELETE CASCADE,
  reusable   boolean NOT NULL DEFAULT false,
  used_at    timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX callbacks_pending_idx ON callbacks (pending_id);

-- What the bot waits for when the next free-text message arrives.
CREATE TABLE chat_state (
  chat_id  bigint PRIMARY KEY,
  awaiting text   NOT NULL CHECK (awaiting IN ('edit_batch','other_date')),
  ref      jsonb  NOT NULL DEFAULT '{}',
  set_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE card_map (
  card_last4      char(4) PRIMARY KEY CHECK (card_last4 ~ '^[0-9]{4}$'),
  account         text NOT NULL,
  account_page_id text NOT NULL,
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sent_log (
  kind                text NOT NULL CHECK (kind IN ('morning','evening','weekly')),
  for_date            date NOT NULL,
  sent_at             timestamptz NOT NULL DEFAULT now(),
  telegram_message_id bigint,
  PRIMARY KEY (kind, for_date)
);

CREATE TABLE bot_log (
  id                bigserial PRIMARY KEY,
  ts                timestamptz NOT NULL DEFAULT now(),
  batch_id          text REFERENCES pending(id) ON DELETE SET NULL,
  item_idx          int,
  input_type        text,
  prefix_used       text,
  router_type       text,
  router_confidence real,
  extractor_type    text,
  model             text,
  tokens_in         int,
  tokens_out        int,
  cost_eur          numeric(10,6),
  latency_ms        int,
  confidence        real,
  was_edited        boolean NOT NULL DEFAULT false,
  edited_fields     text[],
  was_cancelled     boolean NOT NULL DEFAULT false,
  was_undone        boolean NOT NULL DEFAULT false,
  error             text
);
CREATE INDEX bot_log_ts_idx ON bot_log (ts);
CREATE INDEX bot_log_batch_idx ON bot_log (batch_id, item_idx);

CREATE TABLE cache (
  key        text PRIMARY KEY,
  value      jsonb NOT NULL,
  fetched_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE config (
  key   text PRIMARY KEY,
  value jsonb NOT NULL
);

-- Callback actions that change a batch: claiming one also burns its siblings, so
-- "✅ then ❌" or a double tap can only ever run one of them.
CREATE FUNCTION exclusive_actions() RETURNS text[] LANGUAGE sql IMMUTABLE SET search_path = brain, pg_temp
AS $$ SELECT ARRAY['save','cancel','del','undo','acct','type','photo','ncat'] $$;

-- Everything one execution needs, in one round trip.
-- p: {chat_id, cb_token?, take_state?:bool, pending_id?, last_saved?:bool, sched?:{claims:[{kind,for_date}]}}
CREATE FUNCTION load(p jsonb) RETURNS jsonb LANGUAGE plpgsql SET search_path = brain, pg_temp AS $$
DECLARE
  v_chat bigint := (p->>'chat_id')::bigint;
  v_cb callbacks;
  v_state jsonb;
  v_pid text := p->>'pending_id';
  v_claims jsonb := '[]';
  c jsonb;
BEGIN
  IF p ? 'cb_token' THEN
    UPDATE callbacks SET used_at = now()
     WHERE token = p->>'cb_token' AND chat_id = v_chat AND (used_at IS NULL OR reusable)
    RETURNING * INTO v_cb;
    IF v_cb.token IS NOT NULL THEN
      v_pid := coalesce(v_pid, v_cb.pending_id);
      IF v_cb.action = ANY (exclusive_actions()) AND v_cb.pending_id IS NOT NULL THEN
        UPDATE callbacks SET used_at = now()
         WHERE pending_id = v_cb.pending_id AND used_at IS NULL AND action = ANY (exclusive_actions());
      END IF;
    END IF;
  END IF;

  IF coalesce((p->>'take_state')::boolean, false) THEN
    DELETE FROM chat_state WHERE chat_id = v_chat AND set_at > now() - interval '30 minutes'
    RETURNING jsonb_build_object('awaiting', awaiting, 'ref', ref) INTO v_state;
    DELETE FROM chat_state WHERE chat_id = v_chat;   -- drop a stale one too
    v_pid := coalesce(v_pid, v_state->'ref'->>'pending_id');
  END IF;

  IF v_pid IS NULL AND coalesce((p->>'last_saved')::boolean, false) THEN
    SELECT id INTO v_pid FROM pending WHERE chat_id = v_chat AND status = 'saved' ORDER BY saved_at DESC LIMIT 1;
  END IF;

  IF p ? 'sched' THEN
    FOR c IN SELECT * FROM jsonb_array_elements(coalesce(p->'sched'->'claims', '[]')) LOOP
      INSERT INTO sent_log (kind, for_date) VALUES (c->>'kind', (c->>'for_date')::date)
      ON CONFLICT DO NOTHING;
      IF FOUND THEN v_claims := v_claims || c; END IF;
    END LOOP;
  END IF;

  RETURN jsonb_build_object(
    'cb', CASE WHEN v_cb.token IS NULL THEN NULL ELSE to_jsonb(v_cb) END,
    'state', v_state,
    'pending', (SELECT to_jsonb(x) FROM pending x WHERE id = v_pid),
    'card_map', coalesce((SELECT jsonb_agg(to_jsonb(x)) FROM card_map x), '[]'),
    'cache', coalesce((SELECT jsonb_object_agg(key, jsonb_build_object('value', value, 'fetched_at', fetched_at)) FROM cache), '{}'),
    'config', coalesce((SELECT jsonb_object_agg(key, value) FROM config), '{}'),
    'claims', v_claims,
    'open', CASE WHEN p ? 'sched' THEN coalesce((SELECT jsonb_agg(to_jsonb(x) ORDER BY created_at)
              FROM pending x WHERE status IN ('open','retrying','saving')), '[]') END,
    'now', now());
END $$;

-- Applies the write ops an execution produced, all in one transaction.
CREATE FUNCTION apply(ops jsonb) RETURNS int LANGUAGE plpgsql SET search_path = brain, pg_temp AS $$
DECLARE o jsonb; r jsonb; n int := 0;
BEGIN
  FOR o IN SELECT * FROM jsonb_array_elements(coalesce(ops, '[]')) LOOP
    r := o->'row';
    CASE o->>'op'
    WHEN 'pending' THEN
      INSERT INTO pending (id, chat_id, type, payload, telegram_message_id, status, attempts, last_error, reminded_at, saved_at)
      VALUES (r->>'id', (r->>'chat_id')::bigint, r->>'type', r->'payload', (r->>'telegram_message_id')::bigint,
              r->>'status', coalesce((r->>'attempts')::int, 0), r->>'last_error',
              (r->>'reminded_at')::timestamptz, (r->>'saved_at')::timestamptz)
      ON CONFLICT (id) DO UPDATE SET type = EXCLUDED.type, payload = EXCLUDED.payload,
        telegram_message_id = EXCLUDED.telegram_message_id, status = EXCLUDED.status, attempts = EXCLUDED.attempts,
        last_error = EXCLUDED.last_error, reminded_at = EXCLUDED.reminded_at, saved_at = EXCLUDED.saved_at, updated_at = now();
    WHEN 'callbacks' THEN
      INSERT INTO callbacks (token, chat_id, action, data, pending_id, reusable)
      SELECT x->>'token', (x->>'chat_id')::bigint, x->>'action', coalesce(x->'data', '{}'), x->>'pending_id',
             coalesce((x->>'reusable')::boolean, false)
        FROM jsonb_array_elements(o->'rows') x
      ON CONFLICT (token) DO NOTHING;
    WHEN 'burn_callbacks' THEN
      UPDATE callbacks SET used_at = now() WHERE pending_id = o->>'pending_id' AND used_at IS NULL;
    WHEN 'state_set' THEN
      INSERT INTO chat_state (chat_id, awaiting, ref) VALUES ((r->>'chat_id')::bigint, r->>'awaiting', coalesce(r->'ref', '{}'))
      ON CONFLICT (chat_id) DO UPDATE SET awaiting = EXCLUDED.awaiting, ref = EXCLUDED.ref, set_at = now();
    WHEN 'card_set' THEN
      INSERT INTO card_map (card_last4, account, account_page_id) VALUES (r->>'card_last4', r->>'account', r->>'account_page_id')
      ON CONFLICT (card_last4) DO UPDATE SET account = EXCLUDED.account, account_page_id = EXCLUDED.account_page_id, updated_at = now();
    WHEN 'card_del' THEN
      DELETE FROM card_map WHERE card_last4 = o->>'card_last4';
    WHEN 'cache_set' THEN
      INSERT INTO cache (key, value) VALUES (o->>'key', o->'value')
      ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, fetched_at = now();
    WHEN 'cache_del' THEN
      DELETE FROM cache WHERE key = o->>'key';
    WHEN 'config_set' THEN
      INSERT INTO config (key, value) VALUES (o->>'key', o->'value')
      ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
    WHEN 'sent_unclaim' THEN
      DELETE FROM sent_log WHERE kind = o->>'kind' AND for_date = (o->>'for_date')::date;
    WHEN 'sent_msg' THEN
      UPDATE sent_log SET telegram_message_id = (o->>'message_id')::bigint, sent_at = now()
       WHERE kind = o->>'kind' AND for_date = (o->>'for_date')::date;
    WHEN 'log' THEN
      INSERT INTO bot_log (batch_id, item_idx, input_type, prefix_used, router_type, router_confidence, extractor_type,
                           model, tokens_in, tokens_out, cost_eur, latency_ms, confidence, error)
      SELECT x->>'batch_id', (x->>'item_idx')::int, x->>'input_type', x->>'prefix_used', x->>'router_type',
             (x->>'router_confidence')::real, x->>'extractor_type', x->>'model', (x->>'tokens_in')::int,
             (x->>'tokens_out')::int, (x->>'cost_eur')::numeric, (x->>'latency_ms')::int, (x->>'confidence')::real, x->>'error'
        FROM jsonb_array_elements(o->'rows') x
       WHERE x->>'batch_id' IS NULL OR EXISTS (SELECT 1 FROM pending WHERE id = x->>'batch_id');
    WHEN 'log_flag' THEN
      UPDATE bot_log SET
        was_edited    = was_edited    OR coalesce((o->>'was_edited')::boolean, false),
        edited_fields = CASE WHEN o ? 'edited_fields'
                          THEN ARRAY(SELECT DISTINCT unnest(coalesce(edited_fields, '{}') || ARRAY(SELECT jsonb_array_elements_text(o->'edited_fields'))))
                          ELSE edited_fields END,
        was_cancelled = was_cancelled OR coalesce((o->>'was_cancelled')::boolean, false),
        was_undone    = was_undone    OR coalesce((o->>'was_undone')::boolean, false)
      WHERE batch_id = o->>'batch_id' AND extractor_type IN ('finance','task','note','braindump')
        AND (NOT o ? 'item_idx' OR item_idx = (o->>'item_idx')::int);
    ELSE
      RAISE EXCEPTION 'unknown op %', o->>'op';
    END CASE;
    n := n + 1;
  END LOOP;
  RETURN n;
END $$;
COMMIT;
