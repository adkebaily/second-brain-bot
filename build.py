def code(name, lib, key, pos):
    js = (lib + '\n\n// ---- entry ----\n' if key != 'main_prepare_light' else '') + ENTRY[key]
    return {'id': str(uuid.uuid5(uuid.NAMESPACE_URL, name + key)), 'name': name, 'type': 'n8n-nodes-base.code', 'typeVersion': 2,
            'position': pos, 'parameters': {'jsCode': js}}


def pg(name, query, expr, pos):
    return {'id': str(uuid.uuid5(uuid.NAMESPACE_URL, name + query)), 'name': name, 'type': 'n8n-nodes-base.postgres', 'typeVersion': 2.6,
            'position': pos, 'credentials': CRED['postgres'],
            'parameters': {'operation': 'executeQuery', 'query': query, 'options': {'queryReplacement': '={{ [JSON.stringify(' + expr + ')] }}'}}}


def chain(names):
    return {a: {'main': [[{'node': b, 'type': 'main', 'index': 0}]]} for a, b in zip(names, names[1:])}


def pipeline(lib, prep, engine, x0=220):
    return [code('Prepare', lib, prep, [x0, 0]),
            pg('Load', 'select brain.load($1::jsonb) as db', '$json.load', [x0 + 220, 0]),
            code('Engine', lib, engine, [x0 + 440, 0]),
            pg('Apply', 'select brain.apply($1::jsonb) as applied', "$('Engine').first().json.ops", [x0 + 660, 0])]


def workflows(lib, error_id=None):
    settings = {'executionOrder': 'v1', 'timezone': 'Europe/Paris', **({'errorWorkflow': error_id} if error_id else {})}
    wid = lambda s: str(uuid.uuid5(uuid.NAMESPACE_URL, 'second-brain-' + s))
    main_nodes = [{'id': wid('tg'), 'name': 'Telegram Trigger', 'type': 'n8n-nodes-base.telegramTrigger', 'typeVersion': 1.2, 'position': [0, 0],
                   'webhookId': wid('tg-hook'), 'credentials': CRED['telegram'],
                   'parameters': {'updates': ['message', 'callback_query'], 'additionalFields': {}}}]
    main_nodes += pipeline(lib, 'main_prepare', 'main_engine') + [code('Raise errors', '', 'raise', [1100, 0])]
    sched_nodes = [
        {'id': wid('cron'), 'name': 'Every 10 min', 'type': 'n8n-nodes-base.scheduleTrigger', 'typeVersion': 1.2, 'position': [0, 0],
         'parameters': {'rule': {'interval': [{'field': 'cronExpression', 'expression': '*/10 * * * *'}]}}},
        {'id': wid('init'), 'name': 'On n8n start', 'type': 'n8n-nodes-base.n8nTrigger', 'typeVersion': 1, 'position': [0, 200],
         'parameters': {'events': ['init']}},
    ] + pipeline(lib, 'sched_prepare', 'sched_engine') + [code('Raise errors', '', 'raise', [1100, 0])]
    test_nodes = [
        {'id': wid('hook'), 'name': 'Webhook', 'type': 'n8n-nodes-base.webhook', 'typeVersion': 2, 'position': [0, 0], 'webhookId': wid('test-hook'),
         'credentials': CRED['testapi'],
         'parameters': {'httpMethod': 'POST', 'path': 'sb-test', 'authentication': 'headerAuth', 'responseMode': 'responseNode', 'options': {}}},
    ] + pipeline(lib, 'test_prepare', 'test_engine') + [
        {'id': wid('respond'), 'name': 'Respond', 'type': 'n8n-nodes-base.respondToWebhook', 'typeVersion': 1.1, 'position': [1100, 0],
         'parameters': {'respondWith': 'json', 'responseBody': "={{ JSON.stringify($('Engine').first().json.result) }}", 'options': {}}}]
    err_nodes = [{'id': wid('err'), 'name': 'Error Trigger', 'type': 'n8n-nodes-base.errorTrigger', 'typeVersion': 1, 'position': [0, 0], 'parameters': {}},
                 code('Notify Telegram', lib, 'error', [220, 0])]
    sched_conn = chain(['Every 10 min', 'Prepare', 'Load', 'Engine', 'Apply', 'Raise errors'])
    sched_conn['On n8n start'] = {'main': [[{'node': 'Prepare', 'type': 'main', 'index': 0}]]}
    return {
        'SB · Error': {'nodes': err_nodes, 'connections': chain(['Error Trigger', 'Notify Telegram']), 'settings': {'executionOrder': 'v1', 'timezone': 'Europe/Paris'}},
        'SB · Main': {'nodes': main_nodes, 'connections': chain(['Telegram Trigger', 'Prepare', 'Load', 'Engine', 'Apply', 'Raise errors']), 'settings': settings},
        'SB · Scheduler': {'nodes': sched_nodes, 'connections': sched_conn, 'settings': settings},
        'SB · Test API': {'nodes': test_nodes, 'connections': chain(['Webhook', 'Prepare', 'Load', 'Engine', 'Apply', 'Respond']), 'settings': settings},
    }


def syntax_check(lib):
    for key, js in ENTRY.items():
        body = (lib if key != 'raise' else '') + '\n' + js
        src = 'async function __n8n($input, $, $env) {\n' + body + '\n}\n'
        with tempfile.NamedTemporaryFile('w', suffix='.js', delete=False) as f:
            f.write(src)
        r = subprocess.run(['node', '--check', f.name], capture_output=True, text=True)
        os.unlink(f.name)
        if r.returncode:
            sys.exit(f'syntax error in {key}:\n{r.stderr}')


def api(method, path, body=None):
    env = dict(l.split('=', 1) for l in (ROOT / '.env').read_text().split('\n') if '=' in l)
    req = urllib.request.Request(env['N8N_URL'] + '/api/v1' + path, method=method,
                                 headers={'X-N8N-API-KEY': env['N8N_API_KEY'], 'content-type': 'application/json'},
                                 data=json.dumps(body).encode() if body is not None else None)
    try:
        return json.load(urllib.request.urlopen(req))
    except urllib.error.HTTPError as e:
        sys.exit(f'{method} {path} → {e.code} {e.read().decode()[:500]}')


def deploy(lib):
    m = private(json.loads((ROOT / 'config.local.json').read_text()))
    existing = {w['name']: w['id'] for w in api('GET', '/workflows?limit=250')['data'] if not w.get('isArchived')}
    ids = {}
    for name, wf in workflows(lib, None).items():  # Error first: others reference its id
        if name != 'SB · Error' and 'SB · Error' in ids:
            wf = workflows(lib, ids['SB · Error'])[name]
        body = fill({'name': name, **wf}, m)
        if name in existing:
            api('POST', f'/workflows/{existing[name]}/deactivate')
            api('PUT', f'/workflows/{existing[name]}', body)
            ids[name] = existing[name]
        else:
            ids[name] = api('POST', '/workflows', body)['id']
        if name != 'SB · Error':
            api('POST', f'/workflows/{ids[name]}/activate')
        print(f'deployed {name}: {ids[name]}')
    return ids


def main():
    lib = build_lib()
    syntax_check(lib)
    out = ROOT / 'workflows'
    out.mkdir(exist_ok=True)
    for name, wf in workflows(lib).items():
        (out / (re.sub(r'\W+', '_', name.lower()).strip('_') + '.json')).write_text(json.dumps({'name': name, **wf}, ensure_ascii=False, indent=1))
    print(f'lib {len(lib) // 1024} KB, syntax OK, workflows/ written')
    if '--deploy' in sys.argv:
        deploy(lib)


if __name__ == '__main__':
    main()
