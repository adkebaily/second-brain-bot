#!/usr/bin/env python3
"""Build + deploy Second Brain Bot workflows.

  python3 build.py            # build lib, syntax-check, write workflows/*.json
  python3 build.py --deploy   # ...and create/update + activate them via the n8n API (N8N_API_KEY in .env)
"""
import json, os, re, subprocess, sys, tempfile, urllib.request, uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CRED_TYPE = {'telegram': 'telegramApi', 'postgres': 'postgres', 'testapi': 'httpHeaderAuth'}
# Exported workflows/*.json keep placeholders; real ids come from config.local.json (git-ignored) at deploy time.
CRED = {k: {t: {'id': f'__SB_CRED_{k}__', 'name': k}} for k, t in CRED_TYPE.items()}


def private(cfg):
    """Placeholder → real value map from config.local.json."""
    m = {'__SB_CHAT_ID__': cfg['chat_id'], '__SB_BRAIN_DUMP_PAGE__': cfg['brain_dump_page'],
         **{f'__SB_DS_{k}__': v for k, v in cfg['ds'].items()}}
    for k, c in cfg['cred'].items():
        m[f'"__SB_CRED_{k}__"'] = json.dumps(c['id'])
        m[f'"name": "{k}"'] = f'"name": {json.dumps(c["name"])}'
    return m


def fill(wf, m):
    s = json.dumps(wf, ensure_ascii=False)
    for a, b in m.items():
        s = s.replace(a, b)
    left = re.search(r'__SB_[A-Za-z]\w*', s)
    if left:
        sys.exit('unfilled placeholder: ' + left.group(0))
    return json.loads(s)


def parse_prompt(path):
    md = re.sub(r'<!--.*?-->', '', path.read_text(), flags=re.S)
    system = re.search(r'## System prompt\n(.*?)\n## responseSchema', md, re.S).group(1)
    schema = json.loads(re.search(r'## responseSchema\n```json\n(.*?)```', md, re.S).group(1))
    system = '\n'.join(l.rstrip() for l in system.strip().splitlines())
    return {'system': system, 'schema': schema}


def build_lib():
    prompts = {p.stem: parse_prompt(p) for p in sorted((ROOT / 'prompts').glob('*.md'))}
    (ROOT / 'src' / '05_prompts.js').write_text(
        '// GENERATED by build.py from prompts/*.md — edit the .md files, not this.\n'
        f'const PROMPTS = {json.dumps(prompts, ensure_ascii=False, indent=1)};\n')
    return '\n'.join(p.read_text() for p in sorted((ROOT / 'src').glob('*.js')))


